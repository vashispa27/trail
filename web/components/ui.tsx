export type IconName = keyof typeof P;

export const Icon = ({ name, className = "" }: { name: IconName; className?: string }) => (
  <svg className={`oi ${className}`} viewBox="0 0 16 16" aria-hidden="true">
    <path d={P[name]} />
  </svg>
);

export const Avatar = ({ user, lg }: { user: string; lg?: boolean }) => (
  <span className={`avatar${lg ? " lg" : ""}`} style={{ background: `hsl(${hue(user)} 55% 45%)` }} title={user}>
    {handle(user).slice(0, 1).toUpperCase()}
  </span>
);

export function GhAvatar({ github }: { github: string | null }) {
  const owner = ghOwner(github);
  if (!owner) return null;
  // eslint-disable-next-line @next/next/no-img-element
  return <span className="avatar lg"><img src={`https://github.com/${encodeURIComponent(owner)}.png?size=80`} alt="" /></span>;
}

export const When = ({ date }: { date: string | null | undefined }) => (
  <span title={date || ""} suppressHydrationWarning>{ago(date)}</span>
);

